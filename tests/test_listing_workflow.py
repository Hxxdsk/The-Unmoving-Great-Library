def test_profiles_persist_and_reject_changed_button_identity(tmp_path, session):
    path = tmp_path / "workflow.json"
    first = WorkflowStore(path, "店铺A")
    second = WorkflowStore(path, "店铺B")
    with session as s:
        s.check_login()
        s.page.set_content('<button id="next">前往下一步</button>')
        descriptor = s.page.locator("button").evaluate(DESCRIBE)
        first.remember(
            "下一步",
            page_key(s.page),
            [{"kind": "target", "target": descriptor}],
            source="AI",
        )
        assert (
            WorkflowStore(path, "店铺A").recipes("下一步", page_key(s.page))[0][
                "source"
            ]
            == "AI"
        )
        assert second.recipes("下一步", page_key(s.page)) == []
        s.page.locator("button").evaluate("e=>e.textContent='返回列表'")
        assert resolve(s.page, descriptor) is None
        assert "value" not in json.dumps(descriptor)


def test_user_pick_executes_once_then_memory_is_preferred(tmp_path, session):
    store = WorkflowStore(tmp_path / "workflow.json")
    with session as s:
        s.check_login()
        html = (
            '<button id="go" onclick="window.done=(window.done||0)+1">开始制作</button>'
        )
        s.page.set_content(html)
        cancel = threading.Event()

        class Pick(UserGuide):
            def install(self, page, mode):
                super().install(page, mode)
                page.locator("#go").click()
                assert (
                    page.evaluate("window.done || 0") == 0
                ), "指导点击应先拦截，避免重复执行"

        page = DouyinPage(s, cancel, memory=store, guide=Pick(cancel))
        page.click("进入下一步")
        assert s.page.evaluate("window.done") == 1
        assert not store.steps(), "尚未确认结果时不能保存记忆"
        page.wait(lambda: s.page.evaluate("window.done") == 1, "未到下一步")
        recipe = store.recipes("进入下一步", page_key(s.page))[0]
        assert recipe["source"] == "用户指导"
        # IDs generated by the previous document disappear; stable semantics remain.
        s.page.set_content(html)
        logs = []
        page = DouyinPage(s, cancel, logs.append, memory=WorkflowStore(store.path))
        page.click("进入下一步")
        assert s.page.evaluate("window.done") == 2
        assert any("优先使用流程记忆" in line for line in logs)
        page.wait(lambda: s.page.evaluate("window.done") == 2, "未到下一步")


def test_recorded_guidance_is_verified_and_blocks_publish(session):
    with session as s:
        s.check_login()
        s.page.set_content(
            '<button id="bad" onclick="window.bad=true">发布商品</button><button id="ok" onclick="window.ready=true">完成准备</button>'
        )
        cancel = threading.Event()

        class Record(UserGuide):
            def install(self, page, mode):
                super().install(page, mode)
                page.locator("#bad").click()
                page.locator("#ok").click()

        guide = Record(cancel)
        _, actions = guide.run(
            s.page,
            "完成准备",
            mode="record",
            condition=lambda: s.page.evaluate("window.ready||false"),
        )
        assert s.page.evaluate("window.bad===true") is False
        assert actions and actions[-1]["target"]["text"] == "完成准备"
        assert not any(action["target"]["text"] == "发布商品" for action in actions)


