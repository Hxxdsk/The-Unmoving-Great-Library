def test_navigation_repair_is_prioritized_on_next_run(tmp_path, session):
    product = make_product(tmp_path)
    store = WorkflowStore(tmp_path / "workflow.json")
    script = '<script>list=()=>app.innerHTML=\'<div id="new-product"><button>新建商品</button><div id="menu"><button>单商品</button></div></div><button id="repair" onclick="wizard()">手工入口</button>\';list()</script>'
    with session as s:
        s.context.unroute("**/*")
        s.context.route(
            "**/*",
            lambda route: route.fulfill(
                content_type="text/html; charset=utf-8",
                body=FIXTURE.read_text() + script,
            ),
        )
        s.check_login()
        cancel = threading.Event()

        class Repair(UserGuide):
            def install(self, page, mode):
                super().install(page, mode)
                assert mode == "record"
                page.locator("#repair").click()

        page = DouyinPage(s, cancel, memory=store, guide=Repair(cancel))
        page.create(product)
        assert any(
            r["goal"] == "流程：打开单商品创建页"
            for rows in store.steps().values()
            for r in rows
        )
        assert not store.recipes(
            "单商品", "fxg.jinritemai.com/ffa/g/list"
        ), "失败的旧点击不能当作成功记忆"
        logs = []
        page = DouyinPage(s, cancel, logs.append, memory=WorkflowStore(store.path))
        page.create(product)
        assert "/edit" in page.editor_url
        assert any("已按记忆恢复流程" in text for text in logs)


def test_component_close_force_exits_blocked_task_and_driver(tmp_path):
    # A genuine separate component process, with a stuck thread and Playwright
    # driver. No Edge process is launched or killed by this check.
    pid_file = tmp_path / "driver.pid"
    script = r"""
import sys,threading
from pathlib import Path
from PySide6.QtWidgets import QApplication
from PySide6.QtCore import QTimer
from suite.listing.ui import ListingWindow, Worker
from playwright.sync_api import sync_playwright
app=QApplication([])
w=ListingWindow();w.show()
def work(cancel,report,log):
    p=sync_playwright().start()
    Path(sys.argv[1]).write_text(str(p._impl_obj._connection._transport._proc.pid))
    log('ready')
    threading.Event().wait()
w.worker=Worker(work,w)
w.worker.message.connect(lambda _:w.close())
w.worker.start()
QTimer.singleShot(6000,lambda:sys.exit(7))
app.exec()
"""
    result = subprocess.run(
        [sys.executable, "-c", script, str(pid_file)],
        cwd=Path(__file__).resolve().parents[1],
        capture_output=True,
        timeout=10,
    )
    assert result.returncode == 0, result.stderr.decode(errors="replace")
    assert pid_file.exists(), "检查必须真的启动工作线程和浏览器驱动"
    if os.name != "nt":
        pid = int(pid_file.read_text())
        deadline = time.monotonic() + 4
        while time.monotonic() < deadline:
            stat = Path(f"/proc/{pid}/stat")
            if not stat.exists() or stat.read_text().split()[2] == "Z":
                break
            time.sleep(0.1)
        else:
            pytest.fail("关闭组件后 Playwright 驱动仍然运行")


def test_ai_hover_path_is_learned_only_after_success_and_reused(tmp_path, session):
    from test_listing import NavigationClient

    store = WorkflowStore(tmp_path / "workflow.json")
    with session as s:
        s.check_login()
        html = '<style>#choices{display:none}#entry:hover #choices{display:block}</style><div id="entry"><button>创建货品</button><div id="choices"><button onclick="window.total=(window.total||0)+1">独立商品</button></div></div>'
        s.page.set_content(html)
        client = NavigationClient(
            lambda number, _: (
                ("hover", "创建货品") if number == 1 else ("target", "独立商品")
            )
        )
        page = DouyinPage(s, threading.Event(), client=client, memory=store)
        page.click("单商品")
        assert not store.steps()
        page.wait(lambda: s.page.evaluate("window.total") == 1, "没有完成选择")
        recipe = store.recipes("单商品", page_key(s.page))[0]
        assert recipe["source"] == "AI" and recipe["actions"][0]["kind"] == "hover"
        s.page.set_content(html)
        page = DouyinPage(s, threading.Event(), memory=WorkflowStore(store.path))
        page.click("单商品")
        assert s.page.evaluate("window.total") == 2
        assert len(client.calls) == 2, "下次回放不应再请求 AI"


def test_guidance_skip_and_cancel_release_recording(session):
    from suite.listing.models import Cancelled, ListingError

    with session as s:
        s.check_login()
        cancel = threading.Event()
        guide = UserGuide(cancel)
        guide.notify = lambda *_: guide.skip.set()
        with pytest.raises(ListingError, match="跳过"):
            guide.run(s.page, "下一步")
